/* ============================================================
 * نقطة إقلاع لوحة التحكم المنفصلة (admin.html)
 * تسجّل مسار لوحة التحكم فقط، وتعيد توجيه باقي المسارات
 * للموقع الرئيسي (معاينة درس، العودة للموقع)
 * ============================================================ */
(function () {
  Router.register('/admin', AdminView);

  /* لو فُتح admin.html بدون هاش → نبدأ من لوحة التحكم مباشرة */
  if (!location.hash) location.hash = '#/admin';

  /* أي مسار آخر داخل لوحة التحكم → يُعاد فتحه في الموقع الرئيسي */
  Router.setNotFound(function () {
    window.location.href = './index.html' + (location.hash || '');
    return '';
  });

  Router.start();
})();
